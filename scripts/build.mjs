import { build } from "esbuild";
import { readFile } from "node:fs/promises";
import { VERSION } from "../src/common.js";
const pkg = JSON.parse(await readFile("package.json", "utf8"));
if (pkg.version !== VERSION)
  throw new Error("package.json and plugin version differ");
const notices = await readFile("THIRD_PARTY_NOTICES", "utf8");
await build({
  entryPoints: ["src/plugin.js"],
  outfile: "plugin.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  legalComments: "inline",
  banner: {
    js:
      "/*\n" +
      notices.replaceAll("*/", "* /") +
      "\n*/\n// Generated by npm run build; edit src/ instead.",
  },
});
